from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from cooperative.third_party_observation import (
    run_third_party_schmidt_pair_filter,
    run_third_party_target_track_filter,
)
from interfaces.data_objects import ObservationMessage, TargetEstimate
from orbital_core.constants import R_EARTH
from orbital_core.measurements import (
    measure_relative_az_el,
    measure_relative_range,
    measure_relative_range_rate,
)
from orbital_core.metrics import compute_nees_history, compute_rmse
from orbital_core.orbit_elements import keplerian_to_eci
from scenarios.fleet_scenario import generate_fleet_scenario


@dataclass(frozen=True)
class ThirdPartyTrackingSummary:
    mode: str
    run_count: int
    mean_position_rmse: float
    mean_final_position_error: float
    mean_velocity_rmse: float
    mean_final_velocity_error: float
    mean_nees: float
    mean_nis_by_modality: dict[str, float]
    psd_failure_count: int


@dataclass(frozen=True)
class ThirdPartyTrackingExperimentResult:
    propagate_only: ThirdPartyTrackingSummary
    independent_approximation: ThirdPartyTrackingSummary
    schmidt_consistent: ThirdPartyTrackingSummary


def run_v14_third_party_tracking_experiment(
    *, seeds: int = 10, duration: float = 120.0, dt: float = 2.0,
    range_sigma: float = 2.0, range_rate_sigma: float = 0.05,
    az_el_sigma: float = np.deg2rad(0.05),
    process_noise_acceleration: float = 1e-8,
) -> ThirdPartyTrackingExperimentResult:
    """Estimate B at C using physical observations generated by A."""

    if seeds < 1:
        raise ValueError("seeds must be at least one.")
    timestamps = np.arange(0.0, duration + 0.5 * dt, dt)
    base = keplerian_to_eci(
        R_EARTH + 700e3, 0.001, np.deg2rad(23.0), 0.0, 0.0, 0.0
    )
    initial_truth = {
        "sat_a": base + np.array([-1200.0, 80.0, 20.0, 0.0, -0.02, 0.0]),
        "sat_b": base + np.array([900.0, -60.0, 30.0, 0.0, 0.03, 0.0]),
        "sat_c": base + np.array([100.0, 140.0, -20.0, 0.0, 0.0, 0.0]),
    }
    truth = generate_fleet_scenario(
        timestamps=timestamps, initial_state_by_node=initial_truth,
    ).truth_state_history_by_node
    collected = {
        "propagate_only": [],
        "independent_approximation": [],
        "schmidt_consistent": [],
    }
    observer_covariance = np.diag([5.0, 5.0, 5.0, 0.02, 0.02, 0.02]) ** 2
    target_covariance = np.diag([15.0, 15.0, 15.0, 0.05, 0.05, 0.05]) ** 2
    for seed in range(seeds):
        rng = np.random.default_rng(20261330 + seed)
        rate_rng = np.random.default_rng(20261430 + seed)
        angle_rng = np.random.default_rng(20261530 + seed)
        tracks = {
            "sat_a": TargetEstimate(
                estimator_node_id="sat_c", target_node_id="sat_a", timestamp=0.0,
                state_estimate=truth["sat_a"][0] + rng.multivariate_normal(
                    np.zeros(6), observer_covariance
                ),
                covariance=observer_covariance.copy(), quality_score=1.0,
            ),
            "sat_b": TargetEstimate(
                estimator_node_id="sat_c", target_node_id="sat_b", timestamp=0.0,
                state_estimate=truth["sat_b"][0] + rng.multivariate_normal(
                    np.zeros(6), target_covariance
                ),
                covariance=target_covariance.copy(), quality_score=1.0,
            ),
        }
        observations = []
        for index, timestamp in enumerate(timestamps):
            observer = truth["sat_a"][index]
            target = truth["sat_b"][index]
            measurements = (
                (
                    "RANGE", "range",
                    np.array([measure_relative_range(observer, target)
                              + rng.normal(0.0, range_sigma)]),
                    np.array([[range_sigma**2]]),
                ),
                (
                    "RANGE_RATE", "range_rate",
                    np.array([measure_relative_range_rate(observer, target)
                              + rate_rng.normal(0.0, range_rate_sigma)]),
                    np.array([[range_rate_sigma**2]]),
                ),
                (
                    "AZ_EL", "az_el",
                    measure_relative_az_el(observer, target)
                    + angle_rng.normal(0.0, az_el_sigma, 2),
                    np.eye(2) * az_el_sigma**2,
                ),
            )
            for modality, label, measurement, covariance in measurements:
                physical_id = f"sat_a->sat_b:{label}:{index}"
                observations.append(ObservationMessage(
                    message_id=f"{physical_id}:to:sat_c",
                    physical_observation_id=physical_id,
                    observer_id="sat_a", target_id="sat_b",
                    timestamp=float(timestamp), modality=modality,
                    measurement=measurement, covariance=covariance,
                ))
        for mode, selected in (
            ("propagate_only", []),
            ("independent_approximation", observations),
        ):
            history = run_third_party_target_track_filter(
                receiver_id="sat_c", timestamps=timestamps,
                initial_target_estimate_by_id=tracks,
                observation_messages=selected,
                process_noise_acceleration=process_noise_acceleration,
            )
            collected[mode].append(_metrics(history, truth["sat_b"]))
        schmidt = run_third_party_schmidt_pair_filter(
            receiver_id="sat_c", active_target_id="sat_b",
            consider_target_id="sat_a", timestamps=timestamps,
            initial_target_estimate_by_id={
                "sat_a": tracks["sat_a"], "sat_b": tracks["sat_b"],
            },
            observation_messages=observations,
            process_noise_acceleration=process_noise_acceleration,
        )
        collected["schmidt_consistent"].append(
            _metrics(schmidt, truth["sat_b"])
        )
    summaries = {}
    for mode, values in collected.items():
        modalities = sorted({key for value in values for key in value[5]})
        summaries[mode] = ThirdPartyTrackingSummary(
            mode=mode, run_count=len(values),
            mean_position_rmse=float(np.mean([value[0] for value in values])),
            mean_final_position_error=float(np.mean([value[1] for value in values])),
            mean_velocity_rmse=float(np.mean([value[2] for value in values])),
            mean_final_velocity_error=float(np.mean([value[3] for value in values])),
            mean_nees=float(np.mean([value[4] for value in values])),
            mean_nis_by_modality={
                modality: float(np.mean([
                    value[5][modality] for value in values if modality in value[5]
                ]))
                for modality in modalities
            },
            psd_failure_count=sum(value[6] for value in values),
        )
    return ThirdPartyTrackingExperimentResult(
        summaries["propagate_only"],
        summaries["independent_approximation"],
        summaries["schmidt_consistent"],
    )


def _metrics(history, truth):
    estimate = history.state_history_by_target["sat_b"]
    covariance = history.covariance_history_by_target["sat_b"]
    error = estimate - truth
    nees = compute_nees_history(estimate, truth, covariance)
    nis_by_modality: dict[str, list[float]] = {}
    for epoch in history.nis_history:
        for information_id, value in epoch.items():
            modality = (
                "RANGE_RATE" if ":range_rate:" in information_id
                else "AZ_EL" if ":az_el:" in information_id
                else "RANGE"
            )
            nis_by_modality.setdefault(modality, []).append(value)
    return (
        compute_rmse(error[:, :3]), float(np.linalg.norm(error[-1, :3])),
        compute_rmse(error[:, 3:]), float(np.linalg.norm(error[-1, 3:])),
        float(np.mean(nees)),
        {key: float(np.mean(value)) for key, value in nis_by_modality.items()},
        sum(np.linalg.eigvalsh(value).min() < -1e-8 for value in covariance),
    )
